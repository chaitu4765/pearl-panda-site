// Local interaction checks; does not submit any form or contact an external service.
// node scripts/verify-services-cursor.mjs <cdp-url> <path-to-playwright-package>
import { createRequire } from 'node:module'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
const require = createRequire(import.meta.url)
const { chromium } = require(process.argv[3] || 'playwright')
const browser = await chromium.connectOverCDP(process.argv[2])
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
const page = await context.newPage()
const results = [], errors = []
const base = 'http://127.0.0.1:5173'
const cursor = page.locator('.target-cursor-wrapper')
const check = (name, condition) => { assert(condition, name); results.push(name); console.log(`PASS ${name}`) }
page.on('pageerror', error => errors.push(error.message))
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
await fs.mkdir('tmp/verification/services-cursor', { recursive: true })
const hover = async locator => {
  await locator.scrollIntoViewIfNeeded()
  const rect = await locator.boundingBox()
  await page.mouse.move(rect.x + rect.width / 2, rect.y + rect.height / 2)
  await page.waitForFunction(() => document.querySelector('.target-cursor-wrapper')?.dataset.targeting === 'true')
}
const aligned = async selector => {
  await page.waitForFunction(selector => {
    const target = document.querySelector(selector)?.getBoundingClientRect()
    const corners = [...document.querySelectorAll('.target-cursor-corner')].map(corner => corner.getBoundingClientRect())
    if (!target || corners.length !== 4) return false
    return Math.abs(corners[0].left - target.left) < 12 && Math.abs(corners[0].top - target.top) < 12 && Math.abs(corners[2].right - target.right) < 12 && Math.abs(corners[2].bottom - target.bottom) < 12
  }, selector)
}
try {
  await page.goto(`${base}/services`, { waitUntil: 'networkidle' })
  await page.waitForFunction(() => document.querySelector('.target-cursor-wrapper')?.dataset.enabled === 'true')
  check('Services loads without a framework error overlay', await page.locator('vite-error-overlay').count() === 0)
  check('One TargetCursor replaces the old halo on Services', await cursor.count() === 1 && await page.locator('.cursor-halo').count() === 0)
  check('Cursor is decorative and never intercepts clicks', await cursor.getAttribute('aria-hidden') === 'true' && await cursor.evaluate(el => getComputedStyle(el).pointerEvents === 'none'))
  check('Native cursor stays visible before mouse movement', await page.evaluate(() => !document.body.classList.contains('pp-target-cursor-active')))
  const card = page.locator('.ip-service-card').first()
  await hover(card)
  await aligned('.ip-service-card')
  check('Brackets track the lifted service card', await cursor.getAttribute('data-targeting') === 'true')
  check('Native pointer hides only while custom cursor is visible', await page.evaluate(() => document.body.classList.contains('pp-target-cursor-active')))
  await page.screenshot({ path: 'tmp/verification/services-cursor/card.png' })
  const cta = card.locator('a')
  await hover(cta)
  await aligned('.ip-service-card a')
  check('Nested project link gets its own bracket target', true)
  await page.screenshot({ path: 'tmp/verification/services-cursor/link.png' })
  await hover(card)
  await aligned('.ip-service-card')
  check('Moving from link back to card restores the card target', true)
  await page.evaluate(() => window.scrollBy({ top: 70, behavior: 'instant' }))
  await aligned('.ip-service-card')
  check('Brackets follow scroll under a stationary pointer', true)
  await page.setViewportSize({ width: 1350, height: 1000 })
  await aligned('.ip-service-card')
  check('Brackets follow responsive card bounds', true)
  await page.keyboard.press('Tab')
  check('Keyboard use restores native cursor', await page.evaluate(() => !document.body.classList.contains('pp-target-cursor-active')))
  check('Keyboard focus remains visible', await page.evaluate(() => { const el = document.activeElement; return el?.matches(':focus-visible') && getComputedStyle(el).outlineStyle !== 'none' }))
  await hover(cta)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.waitForFunction(() => document.querySelector('.target-cursor-wrapper')?.dataset.enabled !== 'true')
  check('Live reduced-motion change disables animation and restores pointer', await page.evaluate(() => !document.body.classList.contains('pp-target-cursor-active')))
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await hover(cta)
  await aligned('.ip-service-card a')
  check('Cursor can re-enable after preference changes', true)
  await cta.click()
  await page.waitForURL('**/contact?service=Basic%20Portfolio')
  check('Services CTA remains functional with project prefilling', await page.locator('select[name="service"]').inputValue() === 'Basic Portfolio')
  check('Route exit removes target cursor and restores normal halo', await cursor.count() === 0 && await page.locator('.cursor-halo').count() === 1 && await page.evaluate(() => !document.body.classList.contains('pp-target-cursor-active')))
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Services', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('.target-cursor-wrapper')?.dataset.enabled === 'true')
  await hover(page.locator('.ip-service-card').first())
  check('SPA route remount creates exactly one cursor', await cursor.count() === 1)
  await page.mouse.move(20, 150)
  await page.waitForFunction(() => document.querySelector('.target-cursor-wrapper')?.dataset.targeting === 'false')
  check('Leaving targets restores the free-spinning cursor', true)
  await page.locator('#social').scrollIntoViewIfNeeded()
  await hover(page.locator('.ip-social-list > div').first())
  await aligned('.ip-social-list > div')
  check('Social service rows also receive the targeting effect', true)
  check('Informational cards keep non-button semantics', await card.getAttribute('role') === null && await card.getAttribute('tabindex') === null)
  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  const mobilePage = await mobile.newPage()
  await mobilePage.goto(`${base}/services`, { waitUntil: 'networkidle' })
  check('Touch devices keep native behavior with no animated cursor', await mobilePage.evaluate(() => !document.body.classList.contains('pp-target-cursor-active') && document.querySelector('.target-cursor-wrapper')?.dataset.enabled !== 'true'))
  check('Services mobile layout has no horizontal overflow', await mobilePage.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await mobilePage.screenshot({ path: 'tmp/verification/services-cursor/mobile.png' })
  await mobile.close()
  check('No browser runtime errors', errors.length === 0)
  await fs.writeFile('tmp/verification/services-cursor/results.json', JSON.stringify({ passed: results.length, results, errors }, null, 2))
  console.log(`${results.length} Services cursor checks passed.`)
} finally {
  await context.close()
  await browser.close()
}
